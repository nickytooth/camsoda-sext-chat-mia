@app.post("/api/media/offers/{offer_id}/unlock")
async def unlock_media_offer(
    offer_id: str,
    request: IdempotencyRequest,
    user_id: int = Query(default=None),
):
    uid = _commerce_user_id(user_id)
    if not offer_id.isdigit() or len(offer_id) > 20 or int(offer_id) <= 0:
        raise HTTPException(status_code=404, detail="Media offer was not found")
    _require_media_delivery()
    service = _require_commerce_service()
    try:
        result = await service.unlock_offer(uid, offer_id, request.idempotency_key)
    except Exception as exc:
        raise _commerce_http_error(exc) from exc

    entitlement = _commerce_value(result, "entitlement")
    content_id = str(
        _commerce_value(
            entitlement,
            "content_id",
            _commerce_value(result, "content_id", ""),
        )
    )
    if not content_id:
        raise HTTPException(status_code=500, detail="Invalid entitlement response")
    item = _catalog_item(content_id)
    balance = _wallet_balance(result)
    already_unlocked = bool(_commerce_value(result, "already_unlocked", False))

    try:
        await manager.send_json(
            uid,
            {
                "type": "media_entitlement_updated",
                "offer_id": offer_id,
                "content_id": content_id,
                "balance": balance,
            },
        )
    except Exception:
        # The atomic debit/entitlement transaction is already committed. A
        # socket that disappeared between click and response must not turn a
        # successful purchase into a 500; reconnect/history will restore it.
        logger.warning("Entitlement committed but WebSocket notify failed for user %d", uid)
    return {
        "balance": balance,
        "already_unlocked": already_unlocked,
        "entitlement": {
            "content_id": content_id,
            "media_type": item.media_type,
        },
    }



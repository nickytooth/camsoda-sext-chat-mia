class ConnectionManager:
    """Track active WebSocket connections."""

    def __init__(self):
        self.active: dict[int, WebSocket] = {}

    async def connect(self, user_id: int, ws: WebSocket):
        await ws.accept()
        previous = self.active.get(user_id)
        self.active[user_id] = ws
        # One browser reconnect can overlap the old socket's close event. Keep
        # the newest socket authoritative and retire the superseded one; its
        # eventual ``finally`` must not be allowed to remove this replacement.
        if previous is not None and previous is not ws:
            try:
                await previous.close(code=1000, reason="Replaced by a newer connection")
            except Exception:
                logger.debug(
                    "Could not close superseded WebSocket for user %d",
                    user_id,
                    exc_info=True,
                )
        logger.info("WebSocket connected: user %d", user_id)

    def disconnect(self, user_id: int, ws: WebSocket | None = None):
        # A stale socket can finish closing after a reconnect has already put a
        # newer socket in the map. Only its own connection may remove itself.
        if ws is not None and self.active.get(user_id) is not ws:
            logger.debug("Ignoring stale WebSocket disconnect for user %d", user_id)
            return
        self.active.pop(user_id, None)
        logger.info("WebSocket disconnected: user %d", user_id)

    async def send_json(self, user_id: int, data: dict):
        ws = self.active.get(user_id)
        if ws:
            await ws.send_json(data)



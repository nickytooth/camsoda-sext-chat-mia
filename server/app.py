@asynccontextmanager
async def lifespan(app: FastAPI):
    """Initialize DB and providers on startup."""
    global engine, moderation_provider, commerce_service, media_catalog
    global commerce_delivery_ready

    logger.info("Initializing database...")
    await init_db()

    logger.info("Loading persona...")
    persona = load_persona(PERSONA_FILE_SEXTING)
    nsfw_persona = persona  # one always-open persona drives everything
    logger.info("Persona loaded: %s", persona.name)

    # Load and statically validate the authored media catalog on every start.
    # Full object delivery is enabled only when a complete private-R2
    # configuration is present. This keeps ordinary chat available in local
    # environments that have not provisioned their demo media bucket yet.
    from bot.media_commerce import get_media_commerce_service

    commerce_service = get_media_commerce_service()
    media_catalog = commerce_service.catalog
    r2_configured = r2_is_configured()
    commerce_delivery_ready = r2_configured and bool(media_catalog.items)
    if commerce_delivery_ready:
        from bot.media_catalog import validate_catalog_objects

        validate_media_delivery_config()
        logger.info("Validating private R2 media catalog objects...")
        await validate_catalog_objects(media_catalog, r2_object_exists)
        logger.info("Private media delivery ready (%d catalog items)", len(media_catalog.items))
    elif not r2_configured:
        logger.warning(
            "Cloudflare R2 is not configured; wallet/gallery APIs remain available "
            "but chat media offers and unlocks are disabled"
        )
    else:
        logger.warning(
            "The private media catalog is empty; wallet/gallery APIs remain available "
            "but chat media offers and unlocks are disabled"
        )

    logger.info("Initializing LLM providers...")
    # Mia is always-open, so every reply is generated by Grok (nsfw_provider).
    nsfw_provider = GrokProvider()
    classifier_provider = GeminiProvider()
    # thinking_budget=0 → no "thinking" latency; this provider only writes short
    # replies (suggestions + Grok fallback), so speed matters more than reasoning.
    fallback_provider = GeminiProvider(GEMINI_FALLBACK_MODEL, thinking_budget=0)
    # Use the available Gemini path first, then Grok when Gemini returns an
    # invalid/safety-filtered result. Only a failure of both providers blocks
    # fail-closed, so one exhausted API account cannot reject harmless chat.
    moderation_provider = ModerationProviderChain(fallback_provider, nsfw_provider)

    engine = ChatEngine(
        persona=persona,
        nsfw_persona=nsfw_persona,
        nsfw_provider=nsfw_provider,
        classifier_provider=classifier_provider,
        fallback_provider=fallback_provider,
        moderation_provider=moderation_provider,
        commerce_service=commerce_service if commerce_delivery_ready else None,
    )
    logger.info("Chat engine ready")

    yield

    logger.info("Shutting down")


app = FastAPI(title="AI Girlfriend Chat", lifespan=lifespan)

